import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const distHtmlPath = resolve(root, 'dist', 'index.html');
const targetPath = resolve(root, 'server', 'html-template.mjs');

const html = readFileSync(distHtmlPath, 'utf8');
writeFileSync(
  targetPath,
  `// Auto-generated by scripts/bundle-template.mjs from dist/index.html\nexport const HTML_TEMPLATE = ${JSON.stringify(html)};\n`,
  'utf8',
);

if (process.argv.includes('--vercel')) {
  // Remove static dist/index.html so Vercel routes page requests through SSR in api/index.mjs.
  rmSync(distHtmlPath, { force: true });
}
